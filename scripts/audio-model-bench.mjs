// How fast does each model actually run? The measurement the device tier is decided on.
//
// ── WHY THIS IS ITS OWN INSTRUMENT ───────────────────────────────────────────────────────────────────────
// `audio-nam-render-check.mjs` measures whether the plugin PLAYS THE MODEL CORRECTLY, through the plugin's own
// CLAP entry point, on a runner, with an engine build. That is the right tool for correctness and the wrong one
// for comparing six architectures: it builds a whole plugin per model, and the answer here is a RATIO between
// models, measured on ONE machine in one run.
//
// So this times `nam::get_dsp(...)->process()` directly — the exact call the plugin's CLAP `process()` makes,
// with the same engine, the same pin and the same block size — for as many models as it is given. The signal
// path around the model (gate, tone stack, cabinet) is deliberately absent, and that is measured rather than
// assumed: the no-model plugin renders at 632x real time, so the chain is ~0.2% of a WaveNet's cost and the
// model IS the budget. If that ever stops being true this file's numbers stop being a proxy for the plugin's,
// which is why the number is stated in the header rather than left implicit.
//
// ⚠️ A CONTAINER IS SEVERAL MODELS IN ONE FILE. NAM A2's `.nam` is a `SlimmableContainer` — submodels of the
// same amp at different sizes, selected at runtime with `SetSlimmableSize`. That is the feature a Pi-class
// device wants most, because it is a quality/CPU dial rather than a choice of files, so `--slim` measures
// across the dial and the submodel sizes are printed beside the result.
//
// Run:  node scripts/audio-model-bench.mjs --namcore .cache/namcore --models a.nam,b.nam [--slim 0.0,0.5,1.0]
//       (no --namcore? `node scripts/audio-nam-render-check.mjs` documents the checkout; the pin is
//        server/src/lib/namPlugin.js's NAMCORE_REF, and it must be the same commit as the plugin's.)
import { mkdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { COMPILE_FLAGS, compile, namSources, realTimeFactor } from './audio-nam-render-check.mjs';
import { inspectModel } from '../server/src/lib/namPlugin.js';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const log = (m) => console.log(`[model-bench] ${m}`);

/** The bench itself. It has to use the engine's OWN headers and the plugin's sample type, or it times a
 *  different program — `NAM_SAMPLE_FLOAT` is what the plugin compiles with, and double against float is a
 *  throughput difference that has nothing to do with the model. */
const BENCH_SOURCE = `// Generated by scripts/audio-model-bench.mjs — do not edit; it is rewritten on every run.
#include <chrono>
#include <cmath>
#include <cstdio>
#include <cstdlib>
#include <filesystem>
#include <memory>
#include <vector>
#include "NAM/get_dsp.h"
#include "NAM/slimmable.h"

int main(int argc, char** argv) {
  if (argc < 2) { std::fprintf(stderr, "usage: bench <model.nam> [slimmableSize]\\n"); return 2; }
  const double sr = 48000.0;
  const int block = 64;
  const int total = (int)(sr * 4.0);

  std::unique_ptr<nam::DSP> model;
  try {
    model = nam::get_dsp(std::filesystem::path(argv[1]));
  } catch (const std::exception& e) {
    // THE ENGINE'S OWN REFUSAL, reported rather than turned into a number. A model the engine will not load
    // has no throughput, and printing 0x real time for it would read as "very slow" instead of "unloadable".
    std::printf("{\\"model\\":\\"%s\\",\\"error\\":\\"%s\\"}\\n", argv[1], e.what());
    return 0;
  }
  if (!model) { std::printf("{\\"model\\":\\"%s\\",\\"error\\":\\"get_dsp returned null\\"}\\n", argv[1]); return 0; }

  double slim = -1.0;
  bool slimmable = false;
  if (auto* s = dynamic_cast<nam::SlimmableModel*>(model.get())) {
    slimmable = true;
    if (argc > 2) { slim = std::atof(argv[2]); s->SetSlimmableSize(slim); }
  } else if (argc > 2) {
    slim = std::atof(argv[2]);
  }
  model->Reset(sr, block);

  std::vector<NAM_SAMPLE> in(block, (NAM_SAMPLE)0), out(block, (NAM_SAMPLE)0);
  NAM_SAMPLE* ip[1] = { in.data() };
  NAM_SAMPLE* op[1] = { out.data() };
  // Settle the caches before the clock starts, or the first blocks of a WaveNet are measured instead of the
  // model. 200 blocks is ~0.27 s of audio and costs nothing next to a wrong answer.
  for (int i = 0; i < 200; i++) model->process(ip, op, block);

  const auto t0 = std::chrono::steady_clock::now();
  for (int done = 0; done < total; done += block) {
    for (int i = 0; i < block; i++) in[i] = (NAM_SAMPLE)(0.25 * std::sin(2.0 * M_PI * 440.0 * (done + i) / sr));
    model->process(ip, op, block);
  }
  const auto t1 = std::chrono::steady_clock::now();
  const double secs = std::chrono::duration<double>(t1 - t0).count();
  const double audio = (double)total / sr;
  std::printf("{\\"model\\":\\"%s\\",\\"slim\\":%.2f,\\"slimmable\\":%s,\\"processSeconds\\":%.6f,\\"audioSeconds\\":%.3f,\\"blockSize\\":%d}\\n",
              argv[1], slim, slimmable ? "true" : "false", secs, audio, block);
  return 0;
}
`;

/** One build, many runs: the engine compile is a minute and the models are seconds, so the binary is built
 *  once and invoked per model rather than recompiled per model. */
export function modelBench({ namcore, models, slim = [null], work = join(ROOT, '.cache', 'model-bench') }) {
  if (!existsSync(namcore)) {
    console.error(`[model-bench] no engine checkout at ${namcore} — pass --namcore <dir>.`);
    process.exit(2);
  }
  mkdirSync(work, { recursive: true });
  const src = join(work, 'model_bench.cpp');
  writeFileSync(src, BENCH_SOURCE);
  const bin = join(work, 'model_bench');
  const nam = namSources(namcore);
  log(`compiling the bench against ${nam.length} engine sources (once) …`);
  compile([
    ...COMPILE_FLAGS,
    `-I${namcore}`, `-I${join(namcore, 'NAM')}`,
    `-I${join(namcore, 'Dependencies', 'eigen')}`, `-I${join(namcore, 'Dependencies', 'nlohmann')}`,
    src, ...nam, '-o', bin,
  ], 'the model bench');
  log('built');

  const rows = [];
  for (const model of models) {
    for (const s of slim) {
      const benchArgs = [model];
      if (s !== null) benchArgs.push(String(s));
      const run = spawnSync(bin, benchArgs, { encoding: 'utf8' });
      if (run.status !== 0) {
        console.error(`[model-bench] x the bench failed on ${model}:\n${(run.stderr || '').slice(-1000)}`);
        process.exit(1);
      }
      const line = String(run.stdout || '').split('\n').map((l) => l.trim())
        .filter((l) => l.startsWith('{') && l.includes('model')).pop() || null;
      if (!line) { console.error(`[model-bench] x no result line for ${model}`); process.exit(1); }
      const parsed = JSON.parse(line);
      // The weight count comes from OUR inspection rather than the engine's, so a container reports what is
      // actually in the file — and an unloadable model reports why it is unloadable, in the same table.
      let info = null;
      try { info = inspectModel(readFileSync(model, 'utf8')); } catch { info = null; }
      rows.push({
        ...parsed,
        weights: info && info.ok ? info.weights : null,
        submodels: info && info.ok ? (info.submodels || null) : null,
        inspectError: info && !info.ok ? info.reason : null,
        ...(parsed.processSeconds == null ? {} : realTimeFactor(parsed)),
      });
    }
  }
  return rows;
}

// ── CLI ─────────────────────────────────────────────────────────────────────────────────────────────────
const argv = process.argv.slice(2);
const arg = (name, fallback = null) => {
  const at = argv.indexOf(`--${name}`);
  return at !== -1 && argv[at + 1] ? argv[at + 1] : fallback;
};
const isMain = process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url));
if (isMain) {
  const namcore = arg('namcore');
  const models = (arg('models') || '').split(',').map((m) => m.trim()).filter(Boolean);
  if (!namcore || !models.length) {
    console.error('usage: audio-model-bench.mjs --namcore <checkout> --models <a.nam,b.nam> [--slim 0.0,0.5,1.0]');
    process.exit(2);
  }
  const slimArg = arg('slim');
  const slim = slimArg ? slimArg.split(',').map((v) => Number(v.trim())).filter(Number.isFinite) : [null];
  const rows = modelBench({ namcore, models, slim });
  console.log('');
  const name = (p) => String(p).split('/').pop();
  console.log('  model                          slim    weights   real-time factor   faster than real time');
  for (const r of rows) {
    if (r.error) { console.log(`  ${name(r.model).padEnd(30)} —       —         UNLOADABLE: ${r.error}`); continue; }
    const subs = r.submodels ? `  (${r.submodels.map((x) => x.weights).join('/')})` : '';
    console.log(`  ${name(r.model).padEnd(30)} ${(r.slim < 0 ? '—' : r.slim.toFixed(2)).padEnd(7)} `
      + `${String(r.weights ?? '?').padEnd(9)} ${r.realTimeFactor.toFixed(4).padEnd(18)} ${r.timesFaster.toFixed(2)}x${subs}`);
  }
  console.log('');
}
